Use movie_booking_db;

-- 1. Total Bookings
-- What is the total number of bookings made on the platform?

SELECT 
    COUNT(*) AS total_bookings
FROM
    bookings;
    
-- 2. Total Tickets Sold
-- How many tickets have been sold in total?

SELECT 
    SUM(seats_booked) AS total_tickets_sold
FROM
    bookings
WHERE
    booking_status = 'Confirmed';

SELECT 
    *
FROM
    bookings
LIMIT 100;

-- 3. Total Revenue
-- What is the total revenue generated from all bookings?

SELECT 
    SUM(ticket_amount) AS total_revenue
FROM
    bookings
WHERE
    booking_status = 'Confirmed';

-- 4. Average Ticket Price
-- What is the average price per ticket across all bookings?

SELECT 
    ROUND(SUM(ticket_amount) / SUM(seats_booked),
            2) AS ticket_avg_price
FROM
    bookings
WHERE
    booking_status = 'Confirmed';

-- 5. Average Booking Value
-- What is the average amount spent per booking?

SELECT 
    ROUND(AVG(ticket_amount)) AS avg_booking_value
FROM
    bookings
WHERE
    booking_status = 'Confirmed';


-- 6. Booking Cancellation Rate
-- What percentage of bookings are cancelled?

SELECT 
    ROUND(COUNT(CASE
                WHEN booking_status = 'Cancelled' THEN 1
            END) * 100 / COUNT(*),
            2) AS cancellation_rate_percentage
FROM
    bookings;


-- 7. Occupancy Rate
-- What is the seat occupancy rate across all shows?

SELECT 
    SUM(b.seats_booked) * 100 / SUM(t.total_seats) AS occupancy_rate_percentage
FROM
    bookings b
        JOIN
    theatres t ON t.theatre_id = b.theatre_id
WHERE
    b.booking_status = 'Confirmed';

-- 8. Revenue by Movie
-- What is the total revenue generated by each movie?

SELECT 
    m.movie_name, SUM(b.ticket_amount) AS revenue
FROM
    bookings b
        JOIN
    movies m ON m.movie_id = b.movie_id
WHERE
    b.booking_status = 'Confirmed'
GROUP BY m.movie_name
ORDER BY revenue DESC;

-- 9. Revenue by Theatre
-- What is the total revenue generated by each theatre?

SELECT 
    t.theatre_name, SUM(b.ticket_amount) AS revenue
FROM
    bookings b
        JOIN
    theatres t ON b.theatre_id = t.theatre_id
WHERE
    b.booking_status = 'Confirmed'
GROUP BY t.theatre_name
ORDER BY revenue DESC;



-- 10. Revenue by City
-- What is the total revenue generated from each city?

SELECT 
    t.city, SUM(b.ticket_amount) AS revenue
FROM
    bookings b
        JOIN
    theatres t ON b.theatre_id = t.theatre_id
WHERE
    b.booking_status = 'Confirmed'
GROUP BY t.city
ORDER BY revenue DESC;

-- 11. Most Popular Movie
-- Which movie has received the highest number of bookings?

SELECT 
    m.movie_name, COUNT(*) AS highest_booking
FROM
    bookings b
        JOIN
    movies m ON m.movie_id = b.movie_id
GROUP BY m.movie_name
ORDER BY highest_booking DESC
LIMIT 1;


-- 12. Most Popular Genre
-- Which genre is booked the most by customers?

SELECT 
    m.genre, COUNT(*) AS total_bookings
FROM
    bookings b
        JOIN
    movies m ON m.movie_id = b.movie_id
GROUP BY m.genre
ORDER BY total_bookings DESC
LIMIT 1;

-- 13. Peak Booking Hours
-- During which hours of the day are most bookings made?

SELECT 
    HOUR(show_date) AS bookings_hours,
    COUNT(*) AS total_bookings
FROM
    bookings
GROUP BY HOUR(show_date)
ORDER BY total_bookings DESC
LIMIT 10;

-- 14. Peak Show Timings
-- Which show timings are the most preferred by customers?

SELECT 
    TIME(show_date) AS show_time, COUNT(*) AS total_bookings
FROM
    bookings
GROUP BY TIME(show_date)
ORDER BY total_bookings DESC
LIMIT 10;


-- 15. Weekend vs Weekday Bookings
-- How do bookings on weekends compare to weekdays?

SELECT 
    CASE
        WHEN DAYOFWEEK(show_date) IN (1 , 7) THEN 'Weekend'
        ELSE 'Weekday'
    END AS day_type,
    COUNT(*) AS total_bookings
FROM
    bookings
GROUP BY day_type;

-- 16. Payment Method Distribution
-- How are bookings distributed across different payment methods?

SELECT 
    payment_method, COUNT(*) AS total_bookings
FROM
    bookings
GROUP BY payment_method
ORDER BY total_bookings DESC;

-- 17. Customer Retention Rate
-- What percentage of customers return to book again?

SELECT 
    COUNT(DISTINCT CASE
            WHEN bookings_count > 1 THEN customer_id
        END) * 100.0 / COUNT(DISTINCT customer_id) AS retention_rate_percentage
FROM
    (SELECT 
        customer_id, COUNT(*) AS bookings_count
    FROM
        bookings
    GROUP BY customer_id) t;

-- 18. Repeat Customers
-- How many customers have made more than one booking?

SELECT 
    COUNT(*) AS repeat_customers
FROM
    (SELECT 
        customer_id
    FROM
        bookings
    GROUP BY customer_id
    HAVING COUNT(*) > 1) t;

-- 19. Top Spending Customers
-- Which customers have spent the most on bookings?

SELECT 
    c.customer_name, SUM(b.ticket_amount) AS total_spend
FROM
    bookings b
        JOIN
    customers c ON b.customer_id = c.customer_id
WHERE
    b.booking_status = 'Confirmed'
GROUP BY c.customer_name
ORDER BY total_spend DESC
LIMIT 10;

-- 20. Theatre Utilization
-- How efficiently is each theatre's seating capacity being used?

SELECT 
    t.theatre_name,
    SUM(b.seats_booked) * 100 / t.total_seats AS utilization_rate_percentage
FROM
    bookings b
        JOIN
    theatres t ON t.theatre_id = b.theatre_id
WHERE
    b.booking_status = 'Confirmed'
GROUP BY t.theatre_name , t.total_seats
ORDER BY utilization_rate_percentage DESC;


-- 21. Language-wise Revenue
-- What is the total revenue generated by each movie language?

SELECT 
    m.language, SUM(b.ticket_amount) AS total_revenue
FROM
    bookings b
        JOIN
    movies m ON m.movie_id = b.movie_id
GROUP BY m.language
ORDER BY total_revenue;

-- 22. Monthly Revenue Trend
-- How has revenue changed over time on a month-wise basis?

SELECT 
    DATE_FORMAT(show_date, '%Y-%M') AS month,
    SUM(ticket_amount) AS total_revenue
FROM
    bookings
WHERE
    booking_status = 'Confirmed'
GROUP BY month
ORDER BY month DESC;


-- 23. Movie Performance Dashboard
-- What does the overall performance summary of each movie look like - bookings, revenue, occupancy, rating - all in one view?

SELECT 
    m.movie_name,
    COUNT(b.booking_id) AS total_bookings,
    SUM(ticket_amount) AS total_revenue,
    SUM(b.seats_booked) AS total_ticket,
    AVG(b.ticket_amount) AS avg_ticket_value
FROM
    bookings b
        JOIN
    movies m ON m.movie_id = b.movie_id
WHERE
    booking_status = 'Confirmed'
GROUP BY m.movie_name
ORDER BY total_revenue DESC;



-- 24. Executive Booking Dashboard
-- What does the overall booking summary look like - total bookings, total revenue, cancellation rate, occupancy rate,top movie - all in one dashboard view?

SELECT 
    COUNT(*) AS total_bookings,
    SUM(CASE
        WHEN booking_status = 'Confirmed' THEN ticket_amount
        ELSE 0
    END) AS total_revenue,
    SUM(CASE
        WHEN booking_status = 'Cancelled' THEN 1
        ELSE 0
    END) * 100 / COUNT(*) AS cancellation_rate_percentage,
    SUM(CASE
        WHEN booking_status = 'Confirmed' THEN seats_booked
        ELSE 0
    END) AS total_tickets_solds
FROM
    bookings;







